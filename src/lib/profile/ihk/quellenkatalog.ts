//    (quellen-durchsicht/durchsicht.mjs) — im Prompt wäre "Belege aus:
//    Handelskalkulation" sinnlos.
// 2. Bezeichner sind stabil. Wer eine Quelle ausgewählt hat, behält sie über
//    jede Änderung des Katalogs hinweg; bisherige Bezeichner wurden
//    übernommen.
//
